var languages = { en, de, fr, es, it, pt, nl, pl };
function messages(locale = "en") {
  return languages[locale.toLowerCase().split(/[-_]/)[0]] ?? en;
}
var formats = /* @__PURE__ */ new Map();
function number(value, digits = 0, locale = "en") {
  if (typeof value !== "number" || !Number.isFinite(value)) return "\u2014";
  const key = `${locale}:${digits}`;
  if (!formats.has(key)) {
    const options = { minimumFractionDigits: digits, maximumFractionDigits: digits, useGrouping: false };
    try {
      formats.set(key, new Intl.NumberFormat(locale, options));
    } catch {
      formats.set(key, new Intl.NumberFormat("en", options));
    }
  }
  return formats.get(key).format(value);
}

